"""
setup_dataset.py
----------------
One-time script to prepare the Roboflow dataset for training.

What it does:
  1. Copies images + labels from the downloaded folder into backend/dataset/
  2. Splits the 826 training images into train / valid / test (70 / 20 / 10)
  3. Writes a clean data.yaml with absolute paths and renamed classes
  4. Prints a dataset summary

Run once before training:
    python setup_dataset.py

No arguments needed — source path is hard-coded below. Edit SRC if needed.
"""

import os
import shutil
import random
from pathlib import Path

# ── Config ────────────────────────────────────────────────────────────────────

SRC = Path(r"C:/Users/RohitLocal/Downloads/gallstone -v1-using YOLOV 11.yolo26")

DEST        = Path("dataset")
SPLITS      = {"train": 0.70, "valid": 0.20, "test": 0.10}
RANDOM_SEED = 42

# Rename Roboflow class names to cleaner labels
# Original: ['Bladder', 'Gallbladder - v1 2023-10-02 3:36pm', 'Vessels']
CLASS_NAMES = ["Bladder", "Gallbladder", "Vessels"]

# ── Helpers ───────────────────────────────────────────────────────────────────

def copy_file(src: Path, dst: Path):
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)


def count_files(folder: Path, ext: str) -> int:
    return len(list(folder.glob(f"*{ext}"))) if folder.exists() else 0


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    if not SRC.exists():
        print(f"ERROR: Source dataset not found at:\n  {SRC}")
        print("Edit the SRC variable at the top of this script.")
        return

    print(f"Source  : {SRC}")
    print(f"Dest    : {DEST.resolve()}\n")

    # ── Collect all images from the source train/ folder ─────────────────────
    src_img_dir = SRC / "train" / "images"
    src_lbl_dir = SRC / "train" / "labels"

    images = sorted(src_img_dir.glob("*.jpg")) + sorted(src_img_dir.glob("*.png"))
    if not images:
        print("ERROR: No images found in source train/images/")
        return

    print(f"Found {len(images)} images in source.")

    # ── Shuffle and split ─────────────────────────────────────────────────────
    random.seed(RANDOM_SEED)
    random.shuffle(images)

    n_total = len(images)
    n_train = int(n_total * SPLITS["train"])
    n_valid = int(n_total * SPLITS["valid"])
    # test gets the remainder

    split_map = {
        "train": images[:n_train],
        "valid": images[n_train : n_train + n_valid],
        "test":  images[n_train + n_valid :],
    }

    print(f"\nSplit:")
    for name, imgs in split_map.items():
        print(f"  {name:6} : {len(imgs)} images")

    # ── Copy files ────────────────────────────────────────────────────────────
    print("\nCopying files…")
    missing_labels = 0

    for split_name, imgs in split_map.items():
        dst_img = DEST / split_name / "images"
        dst_lbl = DEST / split_name / "labels"
        dst_img.mkdir(parents=True, exist_ok=True)
        dst_lbl.mkdir(parents=True, exist_ok=True)

        for img_path in imgs:
            # Copy image
            shutil.copy2(img_path, dst_img / img_path.name)

            # Copy label (same stem, .txt extension)
            lbl_path = src_lbl_dir / (img_path.stem + ".txt")
            if lbl_path.exists():
                shutil.copy2(lbl_path, dst_lbl / lbl_path.name)
            else:
                # Create an empty label file (background image — valid in YOLO)
                (dst_lbl / (img_path.stem + ".txt")).touch()
                missing_labels += 1

    if missing_labels:
        print(f"  Note: {missing_labels} images had no label file — empty .txt created (background class).")

    # ── Write data.yaml ───────────────────────────────────────────────────────
    abs_dest = DEST.resolve().as_posix()

    yaml_content = f"""# GallScan AI v3 — Dataset
# Auto-generated by setup_dataset.py
# Classes: {CLASS_NAMES}
# Note: This dataset annotates anatomical structures.
#   Class 0 (Bladder)     — urinary bladder region
#   Class 1 (Gallbladder) — gallbladder organ (primary target for gallstone risk)
#   Class 2 (Vessels)     — surrounding vessel structures
# The Gallbladder class localises the organ where gallstones form.

path:  {abs_dest}
train: train/images
val:   valid/images
test:  test/images

nc: {len(CLASS_NAMES)}
names: {CLASS_NAMES}
"""

    yaml_path = DEST / "data.yaml"
    yaml_path.write_text(yaml_content)
    print(f"\nWrote: {yaml_path.resolve()}")

    # ── Verify annotation format ──────────────────────────────────────────────
    print("\nVerifying label format…")
    sample_labels = list((DEST / "train" / "labels").glob("*.txt"))[:5]
    is_segmentation = False
    for lbl in sample_labels:
        lines = lbl.read_text().strip().splitlines()
        for line in lines:
            parts = line.split()
            if len(parts) > 5:
                is_segmentation = True
                break

    fmt = "Segmentation (polygon)" if is_segmentation else "Detection (bounding box)"
    print(f"  Label format detected: {fmt}")

    if not is_segmentation:
        print()
        print("  NOTE: Labels are bounding-box format (5 numbers per line).")
        print("  YOLO26-seg can train on these — it will use boxes as approximate masks.")
        print("  For true pixel masks, run convert_boxes_to_masks.py after setup.")

    # ── Final summary ─────────────────────────────────────────────────────────
    print("\n" + "="*50)
    print("Dataset ready. Summary:")
    for split in ("train", "valid", "test"):
        n_img = count_files(DEST / split / "images", ".jpg") + count_files(DEST / split / "images", ".png")
        n_lbl = count_files(DEST / split / "labels", ".txt")
        print(f"  {split:6}: {n_img} images, {n_lbl} labels")

    print(f"\nClasses : {CLASS_NAMES}")
    print(f"YAML    : {yaml_path.resolve()}")
    print()
    print("Next step:")
    print("  python train.py --data dataset/data.yaml")
    print()
    print("For true segmentation masks (optional, takes longer):")
    print("  python convert_boxes_to_masks.py --split train")
    print("  python convert_boxes_to_masks.py --split valid")


if __name__ == "__main__":
    main()
